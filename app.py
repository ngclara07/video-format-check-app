def discover_input_videos(
) -> list[Path]:

    return sorted(
        [
            path

            for path
            in VIDEO_INPUT_DIR.iterdir()

            if (
                path.is_file()
                and
                path.suffix.lower()
                in SUPPORTED_VIDEO_EXTENSIONS
            )
        ]
    )


def save_uploaded_videos(
    uploaded_files,
) -> list[Path]:

    output_paths: list[
        Path
    ] = []

    for index, uploaded in enumerate(
        uploaded_files
        or [],
        start=1,
    ):

        safe_name = (
            Path(
                uploaded.name
            )
            .name
        )

        target = (
            TEMP_DIR
            /
            (
                f"upload_{index}_"
                + safe_name
            )
        )

        target.write_bytes(
            uploaded.getvalue()
        )

        output_paths.append(
            target
        )

    return output_paths


def copy_inputs(
    input_paths: list[Path],
    destination: Path,
) -> list[Path]:

    destination.mkdir(
        parents=True,
        exist_ok=True,
    )

    copied: list[
        Path
    ] = []

    used_names: set[
        str
    ] = set()

    for index, path in enumerate(
        input_paths,
        start=1,
    ):

        name = (
            path.name
        )

        if name in used_names:

            name = (
                f"{path.stem}"
                f"_{index}"
                f"{path.suffix}"
            )

        used_names.add(
            name
        )

        target = (
            destination
            / name
        )

        shutil.copy2(
            path,
            target,
        )

        copied.append(
            target
        )

    return copied


def save_json(
    path: Path,
    value,
) -> None:

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(
        path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            value,
            file,
            indent=2,
            default=str,
        )


def read_csv_if_exists(
    path: Path,
) -> pd.DataFrame:

    if (
        not path.is_file()
        or
        path.stat().st_size == 0
    ):

        return pd.DataFrame()

    try:

        return pd.read_csv(
            path
        )

    except Exception:

        return pd.DataFrame()


def safe_download(
    label: str,
    path: Path,
    key: str,
    mime: str = "application/octet-stream",
    maximum_inline_mb: float = 150.0,
) -> None:

    if not path.is_file():

        return

    size_mb = (
        path.stat().st_size
        /
        (
            1024
            * 1024
        )
    )

    if (
        size_mb
        > maximum_inline_mb
    ):

        st.warning(
            (
                f"{path.name} is "
                f"{size_mb:.1f} MB. "
                "It remains available in the "
                "generated run directory."
            )
        )

        st.code(
            str(
                path.resolve()
            )
        )

        return

    with open(
        path,
        "rb",
    ) as file:

        st.download_button(
            label=label,
            data=file.read(),
            file_name=(
                path.name
            ),
            mime=mime,
            key=key,
            use_container_width=True,
        )


