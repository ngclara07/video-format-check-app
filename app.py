def normalise_details_dataframe(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """
    Ensure older saved result CSV files can still be displayed.

    New runs always contain the explicit 'stage' column:
        Original
        Converted
    """

    if dataframe.empty:

        return dataframe

    dataframe = (
        dataframe.copy()
    )

    if (
        "stage"
        not in dataframe.columns
    ):

        dataframe[
            "stage"
        ] = "Original"

    dataframe[
        "stage"
    ] = (
        dataframe[
            "stage"
        ]
        .fillna(
            "Original"
        )
    )

    return dataframe


def canonical_converted_files(
    directory: Path,
) -> list[Path]:
    """
    Show only *_convertedOK.mp4 in the principal conversion UI.

    video_format_core.py also creates *_formatOK.mp4, but that
    is an alias and should not appear as a duplicate conversion.
    """

    if not directory.is_dir():

        return []

    return sorted(
        directory.glob(
            "*_convertedOK.mp4"
        )
    )


def find_original_for_converted(
    converted_path: Path,
    inputs_directory: Path,
) -> Path | None:

    stem = (
        converted_path
        .stem
    )

    if stem.endswith(
        "_convertedOK"
    ):

        original_stem = (
            stem[
                :-len(
                    "_convertedOK"
                )
            ]
        )

    else:

        original_stem = (
            stem
        )

    if not inputs_directory.is_dir():

        return None

    matches = [
        path

        for path
        in inputs_directory.iterdir()

        if (
            path.is_file()
            and
            path.stem
            == original_stem
        )
    ]

    if matches:

        return matches[0]

    return None


