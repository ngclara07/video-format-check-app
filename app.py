def show_verification_table(
    rows: pd.DataFrame,
    stage: str,
) -> None:

    if rows.empty:

        st.info(
            (
                "No verification rows are "
                "available for this selection."
            )
        )

        return

    st.dataframe(
        rows[
            [
                "field",
                "expected",
                "actual",
                "status",
            ]
        ],
        hide_index=True,
        use_container_width=True,
    )

    failures = (
        rows[
            rows[
                "status"
            ]
            != "PASS"
        ]
    )

    if failures.empty:

        if (
            stage
            == "Converted"
        ):

            st.success(
                (
                    "✓ CONVERTED FILE VERIFIED — "
                    "all 9 mandatory Exercise 3 "
                    "fields PASS."
                )
            )

        else:

            st.success(
                (
                    "✓ ORIGINAL FILE IS ALREADY "
                    "COMPLIANT — all 9 fields PASS."
                )
            )

    else:

        if (
            stage
            == "Original"
        ):

            st.warning(
                (
                    f"Original submission contains "
                    f"{len(failures)} problematic "
                    "field(s). Automatic conversion "
                    "is required."
                )
            )

        else:

            st.error(
                (
                    f"Converted output contains "
                    f"{len(failures)} failing "
                    "field(s). This should not be "
                    "accepted as compliant."
                )
            )


